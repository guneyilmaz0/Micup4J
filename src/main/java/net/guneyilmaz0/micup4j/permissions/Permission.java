package net.guneyilmaz0.micup4j.permissions;

/** Permission flags defined by the Micup v1 permission registry. */
public enum Permission {
    CREATE_INSTANT_INVITE(0), KICK_MEMBERS(1), BAN_MEMBERS(2), ADMINISTRATOR(3),
    MANAGE_CHANNELS(4), MANAGE_GUILD(5), ADD_REACTIONS(6), VIEW_AUDIT_LOG(7),
    PRIORITY_SPEAKER(8), STREAM(9), VIEW_CHANNEL(10), SEND_MESSAGES(11), SEND_TTS_MESSAGES(12),
    MANAGE_MESSAGES(13), EMBED_LINKS(14), ATTACH_FILES(15), READ_MESSAGE_HISTORY(16),
    MENTION_EVERYONE(17), USE_EXTERNAL_EMOJIS(18), CONNECT(20), SPEAK(21), MUTE_MEMBERS(22),
    DEAFEN_MEMBERS(23), MOVE_MEMBERS(24), USE_VAD(25), CHANGE_NICKNAME(26), MANAGE_NICKNAMES(27),
    MANAGE_ROLES(28), MANAGE_WEBHOOKS(29), MANAGE_EXPRESSIONS(30), USE_EXTERNAL_STICKERS(37),
    MODERATE_MEMBERS(40), CREATE_EXPRESSIONS(43), PIN_MESSAGES(51), BYPASS_SLOWMODE(52),
    UPDATE_RTC_REGION(53), VIEW_CHANNEL_MEMBERS(54);

    private final int bit;
    Permission(int bit) { this.bit = bit; }
    public int getBit() { return bit; }
}
